#!/usr/bin/env python3
"""Compute the provenance distribution of the corpus and the pairing space.

A reviewer's first question about a cross-layer benchmark is what fraction of
it rests on physical measurement versus construction. This script answers it
from the committed adapter outputs rather than from prose, and emits both a CSV
and a paper-ready table block so the number in the paper cannot drift from the
number in the artifact.

Two distributions are reported, because they answer different questions:

  1. ACQUISITION of the underlying events -- was this record captured on real
     hardware or produced by a simulator? This is a property of the source.
  2. PAIRING BASIS of the cross-layer records -- how was a network window
     linked to an autonomy window? This is the schema's honesty flag, and it
     is strictly weaker than (1): two real-testbed sources still yield only a
     synthetic_alignment pairing unless they were captured on ONE platform.

Outputs:
  results/provenance_distribution.csv
  results/paper_figures/block_paperD_tab_provenance.tex
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
STATS = REPO / "results" / "ingest_stats.csv"
OUT_CSV = REPO / "results" / "provenance_distribution.csv"
OUT_TEX = REPO / "results" / "paper_figures" / "block_paperD_tab_provenance.tex"

# Acquisition mode per source, and whether the source observes the autonomy
# layer. Only a source that observes BOTH layers on one platform can ever
# support a measured_same_platform pairing.
SOURCES = {
    "uav_ew_bench_2026": dict(
        acquisition="simulation (physics-informed)", layer="autonomy",
        same_platform=False,
        note="navigation anchor; completion outcomes are Spatial MCR"),
    "uav_attack_whelan": dict(
        acquisition="real testbed", layer="both",
        same_platform=True,
        note="the only source observing a network/RF event and the flight it "
             "degrades on one airframe"),
    "uavids_2025": dict(
        acquisition="simulation (NS-3)", layer="network",
        same_platform=False, note="swarm mesh flows"),
    "hcrl_uavcan": dict(
        acquisition="real testbed", layer="network",
        same_platform=False,
        note="real bus capture, but no autonomy observation to pair with"),
    "datamut_sim": dict(
        acquisition="simulation (event)", layer="network",
        same_platform=False, note="sweepable detector operating point"),
    "uav_cas": dict(
        acquisition="simulation (digital twin)", layer="network",
        same_platform=False, note="release file not locally reachable"),
}


def read_stats() -> dict[str, dict]:
    rows = {}
    with STATS.open() as fh:
        for r in csv.DictReader(fh):
            rows[r["source"]] = dict(
                staged=int(r["staged"]),
                events=int(r["events"]),
                windows=int(r["windows"]),
            )
    return rows


def main() -> int:
    stats = read_stats()

    # datamut_sim is generated by the harness rather than ingested from a
    # release file, so it has no ingest_stats row; take its window count from
    # the committed hop ledger if present.
    ledger = REPO / "results" / "hop_ledger.csv"
    if "datamut_sim" not in stats and ledger.exists():
        with ledger.open() as fh:
            n_hops = sum(1 for _ in csv.DictReader(fh))
        stats["datamut_sim"] = dict(staged=1, events=n_hops, windows=0)

    rows = []
    for src, meta in SOURCES.items():
        s = stats.get(src, dict(staged=0, events=0, windows=0))
        rows.append(dict(
            source=src, **meta,
            staged=s["staged"], events=s["events"], windows=s["windows"],
        ))

    total_events = sum(r["events"] for r in rows)
    real = sum(r["events"] for r in rows if r["acquisition"] == "real testbed")
    sim = total_events - real

    # Pairing space. A pairing needs one network window and one autonomy
    # window; which basis it can carry depends on whether both came from one
    # platform, and whether a named physical relation links them.
    autonomy_windows = sum(r["windows"] for r in rows if r["layer"] in ("autonomy", "both"))
    network_windows = sum(r["windows"] for r in rows if r["layer"] in ("network", "both"))
    measured_capable = sum(r["windows"] for r in rows if r["same_platform"])

    with OUT_CSV.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=[
            "source", "acquisition", "layer", "same_platform",
            "staged", "events", "windows", "event_share_pct", "note"])
        w.writeheader()
        for r in rows:
            r = dict(r)
            r["event_share_pct"] = round(100.0 * r["events"] / total_events, 2) \
                if total_events else 0.0
            w.writerow(r)

    # ---- paper block ------------------------------------------------------
    def esc(s: str) -> str:
        return s.replace("_", r"\_")

    lines = [
        "% MACHINE-GENERATED by experiments/provenance_ledger.py -- do not edit.",
        "% Regenerate after any adapter run; the paper must not drift from the artifact.",
        r"\begin{tabularx}{\columnwidth}{@{}l l r r@{}}",
        r"\toprule",
        r"\textbf{Source} & \textbf{Acquisition} & \textbf{Events} & \textbf{\%}\\",
        r"\midrule",
    ]
    for r in sorted(rows, key=lambda x: -x["events"]):
        share = 100.0 * r["events"] / total_events if total_events else 0.0
        ev = f"{r['events']:,}" if r["events"] else "---"
        sh = f"{share:.1f}" if r["events"] else "---"
        lines.append(f"\\dataset{{{esc(r['source'])}}} & {r['acquisition']} & {ev} & {sh}\\\\")
    lines += [
        r"\midrule",
        rf"\textbf{{real testbed}} & captured on hardware & \textbf{{{real:,}}} & "
        rf"\textbf{{{100.0*real/total_events:.1f}}}\\",
        rf"\textbf{{simulation}} & generated & \textbf{{{sim:,}}} & "
        rf"\textbf{{{100.0*sim/total_events:.1f}}}\\",
        r"\bottomrule",
        r"\end{tabularx}",
    ]
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text("\n".join(lines) + "\n")

    summary = dict(
        total_events=total_events, real_events=real, sim_events=sim,
        real_pct=round(100.0 * real / total_events, 2) if total_events else 0.0,
        autonomy_windows=autonomy_windows, network_windows=network_windows,
        measured_same_platform_capable_windows=measured_capable,
    )
    print(json.dumps(summary, indent=2))
    print(f"-> {OUT_CSV.relative_to(REPO)}")
    print(f"-> {OUT_TEX.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
