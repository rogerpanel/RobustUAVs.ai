#!/usr/bin/env python3
"""P3: emit drop-in pgfplots coordinate blocks + table values for both papers.

Reads ONLY committed results/ CSVs (clean campaign, 2026-07-28) and writes
results/paper_figures/*.tex plus a provenance README. Every file carries a
provenance banner: real-corpus / simulation-derived / fixture-derived /
published-value / calibration-pending. Do not hand-edit the .tex outputs;
re-run this script.
"""
from __future__ import annotations

import csv
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "results"
OUT = RESULTS / "paper_figures"

BANNER = ("% AUTO-GENERATED by experiments/make_paper_figures.py "
          "(clean campaign 2026-07-28).\n"
          "% PROVENANCE: {prov}\n"
          "% Do not hand-edit; re-run the script.\n")


def load(name):
    return list(csv.DictReader(open(RESULTS / name)))


def coords(pairs, fmt="({:g},{:.3f})"):
    return "".join(fmt.format(x, y) for x, y in pairs)


def write(name, prov, body):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(BANNER.format(prov=prov) + body)
    print(f"[figures] wrote results/paper_figures/{name}")


# ----------------------- Paper C: operating curve -----------------------

def fig_opcurve():
    rows = load("theta_operating_curve.csv")
    body = []
    for scen in ("1", "2", "3"):
        for mode in ("low", "medium"):
            pts = [(float(r["epsilon"]), float(r["recall"]))
                   for r in rows if r["scenario"] == scen and r["mode"] == mode]
            pts.sort()
            body.append(f"% scenario {scen} ({'grid4x4' if scen == '1' else 'ring9' if scen == '2' else 'double-ring'}), {mode} mode "
                        f"(U[1,{'7' if mode == 'low' else '10'}] s), 8 seeds x 4 policies, FPR=0 throughout\n"
                        f"\\addplot coordinates {{{coords(pts)}}};\n")
    body.append(
        "% NOTE: replaces the pre-2026-07-28 curve, which was contaminated by\n"
        "% a workdir-accumulation bug in sweep_theta.py (recall increasing in\n"
        "% epsilon in medium mode was the visible symptom). The loose-epsilon\n"
        "% plateaus (low 0.125-0.312, medium 0.625-0.656 by topology) are the\n"
        "% missed-contact-window self-exposure floor, NOT path deviation -\n"
        "% see docs/certified_regime_analysis.md Finding 3.\n")
    write("paperC_fig3_opcurve.tex",
          "simulation-derived (local patched DATAMUt replay, deterministic per seed)",
          "".join(body))


